	BEQ.w	.FIRST	;beq.s->beq.w
	LEA	OBJBASE,A0
	
	rept	OBJLEN/4
	move.l	(a5),d0
	move.l	(a0),(a5)+
	move.l	d0,(a0)+
	endr
	lea	-OBJLEN(a5),a5
	RTS
	
.FIRST:
	JSR	DOINITIALDMA
	jsr	OBJRANGE			; check if object is too far from bubsy
	bcc.s	.INRANGE
	jmp	CLEAROBJWVRAM

.INRANGE:					;check if we collided with crate
	AND.B	#~BOSSFLAG,GAMEFLAG1

	MOVE	OBJX(A5),D0							;dont let bubsy run back
	SUB.w	WINDX,D0
	CMP.w	#320+$20,D0
	BCC.s	.NOBACK

	MOVE.w	OBJY(A5),D0
	ADD.w	#160,D0
	SUB.w	BUBY,D0
	BMI.s	.NOBACK

	OR.B	#BOSSFLAG,GAMEFLAG1						;use boss flag to align screen
	
.NOBACK:
.NOPRIORITY:									;process state
	moveq	#DONESPINNING,D0
	and.B	OBJFLAGS(A5),D0
	BEQ.s	.NOTDONESPINNING
	
.DONESPINNING:
	moveq	#FADING,D0
	and.B	OBJFLAGS(A5),D0
	BNE.s	.FADEOUT

	AND.B	#~TIMEFLAG,GAMEFLAG1						;stop the clock
	
	MOVE.B	OBJAUX4(A5),D0
	ADDQ.B	#1,d0
	move.b	d0,OBJAUX4(A5)
	
.NODMA:
	CMP.B	#40,D0
	BNE.s	.STILLWAIT
	JSR	STARTTALLY
	JMP	CLEAROBJWVRAM
	
.STILLWAIT:
.FADEOUT:
	JMP	ENEMYOAMS

.NOTDONESPINNING:
	moveq	#SPINNING,D0
	and.B	OBJFLAGS(A5),D0							;see if we should start of if we are
	BNE	.SPINNING
	
.NOTSPINNING:
	MOVEq	#0,D0
	JSR	ENEMYCOLLIDE
	BCS.s	.COLISION
	
.NOCOLISION:
	JMP	ENEMYOAMS

.COLISION:
	TST.w	TIME
	BEQ.s	.NOCOLISION						;no collision if bubsy is out of time
	AND.B	#~TIMEFLAG,GAMEFLAG1					;stop the clock

	move.w	WINDX,d0
	MOVE.w	d0,WINDXMIN						;freeze wind horizontally
	MOVE.w	d0,BUBXMIN
	MOVE.w	d0,BUBXMAX
	ADD.w	#$10,BUBXMIN
	ADD.w	#320-$10,BUBXMAX

	MOVEq	#POPSOUND5,D0					;start spinning based on vx
	JSR	STARTSOUND

	OR.B	#SPINNING,OBJFLAGS(A5)

	MOVE.w	BUBVX,D0
	BPL.s	.VPL
	NEG	D0
	
