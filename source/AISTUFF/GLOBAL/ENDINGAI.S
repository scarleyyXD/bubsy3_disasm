	LSR.B	#1,D0
	MOVE.B	OBJAUX3(A5),D1
	ADDX.B	D1,D0
	MOVE.B	D0,OBJAUX3(A5)
	CMP.B	#$8,D0
	BCS.s	.DRAWFRAME

	MOVE.B	OBJFRAME(A5),D0
	move.B	D0,OBJAUX7(A5)
	and.b	#1,D0
	BNE.s	.NOYARN

	CMP.B	#1,OBJAUX4(A5)
	BLE.s	.NOYARN
