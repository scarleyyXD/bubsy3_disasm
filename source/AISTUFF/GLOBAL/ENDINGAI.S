	MOVE.B	D0,OBJAUX3(A5)
	ROR.w	#8,D0
	MOVE.B	D0,OBJAUX4(A5)

	CLR.w	SHADOWTIMER
	CLR.w	INVTIMER					;kill all other objects, cancel all VDMA
	JSR	REQDMAFORTALLY

