	AND.B	#~TIMEFLAG,GAMEFLAG1				;stop the clock

	moveq	#ANCHORFLAG,D0
	and.B	BUBSYFLAGS,D0
	BNE.s	.NOSCROLL
	MOVE	BUBVY,D0
	BPL.w	.SCROLL
	
