SUPERSPEED	equ	7

SUPERYARNAI:
	JSR	DOINITIALDMA
	JSR	OBJRANGE
	BCC.s	.INRANGE
	JMP	CLEAROBJWVRAM

.INRANGE:
	JSR	CLIPY
	JSR	ENEMYCOLLIDE
	BCC.s	.NOCOLLIDE

	moveq	#$77,d2
	lea	SCORE+3,a0
	AND	#~%10000,CCR	;and.w->and
	MOVE.B	STIMER+1,D0
	AND.B	d2,D0
	MOVE.B	(a0),D1
	ABCD	D0,D1
	MOVE.B	D1,(a0)
	MOVE.B	STIMER,D0
	AND.B	d2,D0
	MOVE.B	-(a0),D1
	ABCD	D0,D1
	MOVE.B	D1,(a0)
	sf	D0
	MOVE.B	-(a0),D1
	ABCD	D0,D1
	MOVE.B	D1,(a0)
	MOVE.B	-(a0),D1
	ABCD	D0,D1
	MOVE.B	D1,(a0)

	lea	YARNS+1,a0
	MOVEq	#$50,D0
	AND	#~%10000,CCR	;and.w->and
	MOVE.B	(a0),D1
	ABCD	D0,D1
	MOVE.B	D1,(a0)
	sf.B	D0
	MOVE.B	-(a0),D1
	ABCD	D0,D1
	MOVE.B	D1,(a0)

	MOVEq	#WOLGASMSOUND,D0
	JSR	STARTSOUND

	moveq	#0,D6
	moveq	#0,D7
	JSR	FORCEDBOP

.NOCOLLIDE:
	move.b	OBJAUX0(A5),d1
	addq	#1,d1
	CMP.B	#SUPERSPEED,d1
	BNE.s	.DRAWFRAME
	moveq	#0,d1

	move.b	OBJFRAME(a5),d0
	addq	#1,d0
	and.b	#%111,d0
	move.b	d0,OBJFRAME(a5)

.DRAWFRAME:
	move.b	d1,OBJAUX0(A5)
	JMP	ENEMYOAM