RECYCLEAI:
	JSR	DOINITIALDMA
	JSR	OBJRANGE
	BCC.s	.INRANGE
	JMP	CLEAROBJWVRAM

.INRANGE:
	JSR	CLIPY
	JSR	ENEMYCOLLIDE
	BCC.s	.CHECKFRAME

	MOVEq	#CONTINUESOUND,D0				;give another continue
	JSR	STARTSOUND

	ADDQ.B	#1,CONTINUES
	moveq	#0,d6
	moveq	#0,d7
	JSR	FORCEDBOP

.CHECKFRAME:
	moveq	#%011,D0
	and.w	STIMER,D0
	BNE.s	.DRAWFRAME

	move.b	OBJAUX0(A5),d0
	addq.b	#1,d0
	move.b	d0,OBJAUX0(a5)
	lsr.b	#1,D0
	and.w	#7,d0
	move.b	d0,OBJFRAME(a5)
	
.DRAWFRAME:
	JMP	ENEMYOAM