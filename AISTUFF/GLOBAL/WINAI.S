
WINAI
	st.b	NoWater

	OR.B	#NOPAUSEFLAG,GAMEFLAG1					;DEFEAT PAUSE

	MOVE	PLAYER,D0
	BEQ	.P10
	MOVE.B	#'2',STRIPBUF+PLRNUM_WIN					;load player number if 2
.P10

	MOVE.B	#%11100110,D6						;flash winner
	MOVE.B	STIMER+1,D0
	AND.B	#1,D0
	BEQ	.B01A
	MOVE.B	#%11000110,D6
.B01A	
	MOVE.B	D6,STRIPBUF+WINCOL
	
	MOVE.B	#%11100110,D6						;flash cursor
	MOVE.B	STIMER+1,D0
	AND.B	#1,D0
	BEQ	.B10
	MOVE.B	#%11000110,D6
.B10	
	LEA	STRIPBUF+YESCOL_WIN,A0
	MOVE	D6,D0
	CLR	D6
	MOVE.B	OBJAUX5(A5),D6
	MOVE.B	D0,(A0,D6.W)
	EOR	#NOCOL_WIN-YESCOL_WIN,D6
	MOVE.B	#%11100110,(A0,D6.W)

	MOVE.B	FADEDIR,D0						;handle clock
	BNE	.FADING
	SUBQ.B	#1,OBJAUX6(A5)
	BNE	.CLOCKDONE
	SUBQ.B	#1,OBJAUX7(A5)
	BPL	.C1

	MOVE.B	#$FC,FADEDIR						;out of time
	BRA	.FADING

.C1									;not out of time run clock
	MOVE.B	FrameRate+1,OBJAUX6(A5)
	MOVE.B	OBJAUX7(A5),D0
	ADD.B	#'0',D0
	MOVE.B	D0,STRIPBUF+CONTDIGITS_WIN+1
	MOVE.B	#' ',STRIPBUF+CONTDIGITS_WIN

.CLOCKDONE
	JSR	LRSOUND

	MOVE	EDGESTICK,D0						;check sounds
	AND	#JOY_LEFT,D0
	BEQ	.NOTLEFT
	MOVE.B	#0,OBJAUX5(A5)
.NOTLEFT

	MOVE	EDGESTICK,D0
	AND	#JOY_RIGHT,D0
	BEQ	.NOTRIGHT
	MOVE.B	#NOCOL_WIN-YESCOL_WIN,OBJAUX5(A5)
.NOTRIGHT

	MOVE	EDGESTICK,D0
	AND	#JOY_A+JOY_B+JOY_X+JOY_Y,D0
	BEQ	.NOBUTTONS
	MOVE.B	#$FC,FADEDIR
.NOBUTTONS

	MOVE	EDGESTICK,D0
	AND	#JOY_START,D0
	BEQ	.NOSTART
	MOVE.B	#$FC,FADEDIR
.NOSTART

	MOVE.B	FADEVAL,D0						;if faded out analyse cursor
	AND.B	#$F0,D0
	BNE	.NOTFADED
	MOVE.B	OBJAUX5(A5),D0
	BEQ	.WIN
.NOWIN

	AND.B	#~NOPAUSEFLAG,GAMEFLAG1					;enable pause
	MOVE	#$FFFF,CONTINUES					;restore current player
	sf.b	NoWater
	JMP	PLAYERTURNOVER
.NOTFADED

.FADING
	MOVE.L	#STRIPBUF,OBJAUX0(A5)
	JSR	DRAWTEXT

	MOVE	CONTINUES,D0						;see if sould continue or try see if player is alive
	BPL	.PLRALIVE
	AND.B	#%0000000010000000,D0
	BNE	.TRY
.PLRALIVE

	MOVE.L	#STRIPBUF+CONTTXT,OBJAUX0(A5)
	JSR	DRAWTEXT

	MOVE.B	OBJAUX5(A5),D6						;draw yarn cursor
	ADD.L	#OBJLEN,A5
	MOVE	WINDY,OBJY(A5)
	ADD	#$0097,OBJY(A5)

	MOVE	#$5C,D0
	CMP.B	#0,D6
	BEQ	.YES
	MOVE	#$AA,D0
.YES
	ADD	WINDX,D0
	MOVE	D0,OBJX(A5)						;position

	MOVE	STIMER,D0
	ASL	#2,D0
	JSR	GETSIN
	ASL	#4,D0
	AND	#$FF00,D0
	BPL	.XPOS
	OR	#$00FF,D0
.XPOS
	ROL	#8,D0
	ADD	D0,OBJX(A5)

	MOVE	STIMER,D0
	ASL	#3,D0
	JSR	GETSIN
	ASL	#4,D0
	AND	#$FF00,D0
	BPL	.YPOS
	OR	#$00FF,D0
.YPOS
	ROL	#8,D0
	ADD	D0,OBJY(A5)

	MOVE	#$E3EC,OBJOAM0(A5)					;set up OAM
	MOVE.L	#YARNMAP,OBJMAP(A5)
	JMP	ENEMYOAMS

.TRY
	MOVE.L	#STRIPBUF+TRYTXT,OBJAUX0(A5)				;draw try again text
	JMP	DRAWTEXT

.WIN
	AND.B	#NOPAUSEFLAG,GAMEFLAG1					;enable pause
	sf.b	NoWater
	JMP	PLAYERTURNOVER

SPACING4	equ	$C
WINTEXT	;123456789ABCDEF0123456789ABCDEF
	dc.b	$FD							;,<SPACING4,>SPACING4
	dc.B	(SPACING4&$ff00)>>8,(SPACING4&$ff)
	
WINCOL	equ	*+1-WINTEXT
 	dc.b	$FE,%11100110
	dc.b	$FF,0-$0D*SPACING4/2+$80,$00,$40,$00
	dc.b	'PLAYER '
PLRNUM_WIN	equ	*-WINTEXT
	dc.b	'1 WINS!',0

CONTTXT	equ	*-WINTEXT
 	dc.b	$FE,%11100110
	dc.b	$FF,0-$09*SPACING4/2+$80,$00,$50,$00
	dc.b	'CONTINUE.'
	dc.b	$FF,0-$02*SPACING4/2+$80,$00,$70,$00
CONTDIGITS_WIN	equ	*-WINTEXT
	dc.b	'10'
	dc.b	$FF,0-$09*SPACING4/2+$80,$00,$90,$00
YESCOL_WIN	equ	*+1-WINTEXT
 	dc.b	$FE,%11100110
	dc.b	'YES'
NOCOL_WIN	equ	*+1-WINTEXT
 	dc.b	$FE,%11100110
	dc.b	'    NO',0

TRYTXT	equ	*-WINTEXT
 	dc.b	$FE,%11100110
	dc.b	$FF,0-$0B*SPACING4/2+$80,$00,$70,$00
	dc.b	'PRESS START'
	dc.b	$FF,0-$0C*SPACING4/2+$80,$00,$80,$00
	dc.b	'TO TRY AGAIN',0

